private val RELATIONSHIP_MULTIPLICATION_ROW = Regex("""(\d+)\s*[\u00D7x]\s*(\d+)\s*=\s*(\d+)""")

private const val RELATIONSHIP_CAT = "\uD83D\uDC31"

private fun isRelationshipCatGrid(text: String?): Boolean {
    val value = text ?: return false
    if (value.isBlank()) return false
    return value.replace(RELATIONSHIP_CAT, "").isBlank()
}

